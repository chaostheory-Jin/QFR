import fs from 'node:fs/promises';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const dir=fileURLToPath(new URL('.',import.meta.url));
const english=process.env.VIDEO_LANGUAGE==='en';
const out=fileURLToPath(new URL(english?'../../outputs/feature-videos-20261030-en/':'../../outputs/feature-videos-20261029/',import.meta.url));
const ffmpeg=dir+'encoder/imageio_ffmpeg/binaries/ffmpeg-macos-aarch64-v7.1';
await fs.mkdir(out,{recursive:true});
const run=args=>new Promise((resolve,reject)=>{let log='';const p=spawn(ffmpeg,args);p.stderr.on('data',d=>log+=d);p.on('error',reject);p.on('close',c=>c===0?resolve(log):reject(new Error(log)));});
const kind=process.argv[2];
const data=JSON.parse(await fs.readFile(dir+kind+(english?'-en':'')+'-video.json','utf8'));
const info=await run(['-hide_banner','-i',data.path,'-f','null','-']);
const durationMatch=info.match(/Duration: (\d+):(\d+):([\d.]+)/);
const duration=+durationMatch[1]*3600+ +durationMatch[2]*60+ +durationMatch[3];
const trim=2.5;
const speed=Math.max(1,Math.min(1.35,(duration-trim)/135));
const filename=(kind==='payroll'?'Payroll-Feature-Demo':'Cola-Reconciliation-Feature-Demo')+(english?'-English':'')+'.mp4';
await run(['-y','-hide_banner','-ss',String(trim),'-i',data.path,'-vf',`setpts=PTS/${speed},fps=30`,'-c:v','libx264','-preset','medium','-crf','20','-pix_fmt','yuv420p','-movflags','+faststart','-an','-metadata',`title=${kind==='payroll'?'Payroll':'Cola Reconciliation'} | Product demonstration`,'-metadata',`comment=Fictional sample data. ${english?'English':'Chinese'} step captions. No real payments or live AI extraction. Browser-only demonstration.`,out+filename]);
await run(['-y','-hide_banner','-ss','5','-i',out+filename,'-frames:v','1',out+filename.replace('.mp4','-preview.png')]);
const result=await run(['-hide_banner','-i',out+filename,'-f','null','-']);
console.log(filename, result.match(/Duration: [^\n]+/)[0],result.match(/Video: [^\n]+/)[0]);
await fs.writeFile(dir+kind+'-encoding.json',JSON.stringify({filename,duration,trim,speed,finalDuration:(duration-trim)/speed,bytes:(await fs.stat(out+filename)).size},null,2));
